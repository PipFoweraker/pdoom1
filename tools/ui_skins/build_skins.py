#!/usr/bin/env python3
"""build_skins.py -- turn tools/ui_skins/specs/*.json into godot/data/ui_skins.json.

Each spec names a mockup image, a box per colour token (sampled by sample_palette.py), and
a "skin" block: display_name, font_names, corner_radius, border_width, and "overrides" --
tokens set BY HAND, each carrying a "hand" reason so a reader can tell sampled from chosen.

The output is the file ThemeManager reads at boot. Every token keeps its provenance: the
"source" field names the spec and image; hand-set tokens stay {"hex", "hand"} dicts.

USAGE:
  python tools/ui_skins/build_skins.py --images G:/Downloads/someuiconcepts
  python tools/ui_skins/build_skins.py --images DIR --check   # exit 1 if the json is stale

The mockups are third-party art and are NOT in git, so --check is a local tool, not a CI
gate. Re-run it whenever a spec box or override changes.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from sample_palette import resolve_image, sample  # noqa: E402

REPO = HERE.parents[1]
OUT = REPO / "godot" / "data" / "ui_skins.json"
SPECS = HERE / "specs"

HEADER = (
    "GENERATED by tools/ui_skins/build_skins.py from tools/ui_skins/specs/*.json -- do not "
    "hand-edit; change a spec and re-run. Tokens are sampled from mockup images; a "
    "{hex, hand} token was set by hand and says why."
)


def build(images: Path) -> dict:
    skins = {}
    for spec_path in sorted(SPECS.glob("*.json")):
        spec = json.loads(spec_path.read_text(encoding="utf-8"))
        meta = spec["skin"]
        img = Image.open(resolve_image(spec["image"], images))
        palette: dict = {}
        gradient: list = []
        for name, t in spec["tokens"].items():
            val = sample(img, t["box"], t.get("mode", "bg"), t.get("stops", 2))
            if name == "bg_gradient":
                gradient = val
            else:
                palette[name] = val
        for name, ov in meta.get("overrides", {}).items():
            palette[name] = ov
        skin = {
            "display_name": meta["display_name"],
            "source": f"tools/ui_skins/specs/{spec_path.name} <- {spec['image']}",
            "palette": palette,
            "font_names": meta["font_names"],
            "corner_radius": meta["corner_radius"],
            "border_width": meta["border_width"],
        }
        if gradient:
            skin["bg_gradient"] = gradient
        skins[spec_path.stem] = skin
    return {"_comment": HEADER, "skins": skins}


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--images", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = json.dumps(build(args.images), indent=2) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"STALE: {OUT} differs from the specs; re-run without --check")
            return 1
        print("ui_skins.json matches the specs")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
